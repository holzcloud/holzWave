# The output file of the app's own build script holds the line `cargo:rustc-cfg=dev` exactly when Tauri was told this is a
# development build. The check-cfg line proves that the file is the one of the Tauri build script and not another.
dev_check() { # dev_check <label> <target folder>
    file=$(ls -t "$2"/release/build/holzwave-app-*/output 2>/dev/null | head -n 1)
    [ -n "$file" ] || fail "$1: no output file of the app's build script below $2"
    grep -qx 'cargo:rustc-check-cfg=cfg(dev)' "$file" || fail "$1: $file is not the output of the Tauri build script"
    if grep -qx 'cargo:rustc-cfg=dev' "$file"; then
        echo "$1: DEVELOPMENT build (the build script output has cargo:rustc-cfg=dev)"
        return 1
    fi
    echo "$1: not a development build (no cargo:rustc-cfg=dev in $file)"
    return 0
}

