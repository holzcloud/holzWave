#!/bin/sh
# The Flatpak of holzWave: check its three files from a Mac, build and install it on a Linux machine.
#
#   sh scripts/build-flatpak.sh --check            validate the manifest, the AppStream file and the desktop file (Docker)
#   sh scripts/build-flatpak.sh --container-build  build the Flatpak in a privileged Docker container (slow, Docker)
#   sh scripts/build-flatpak.sh --engine-offline   build the terminal engine with the network cut, from hashed sources (Docker)
#   sh scripts/build-flatpak.sh                    build the Flatpak and install it for the user (a Linux machine)
#
# Status: unverified. Flatpak ships in 0.0.1 only if it builds on the owner's Linux machine and row L10 of
# docs/test-plan.md passes (docs/flatpak.md).
#
# --check runs in a Docker container (image `holzwave-flatpak-check`: Ubuntu 26.04 with flatpak-builder, appstream and
# desktop-file-utils, built on the first run, `docker rmi holzwave-flatpak-check` forgets it). The three files are
# mounted read-only. Three validators must pass, and the script prints `flatpak-check: ok` as its last line only then:
#
#   flatpak-builder --show-manifest    parses the manifest; it exits 0 for a manifest it cannot fully read and only
#                                      prints a warning, so any output on stderr fails the check, and the parsed
#                                      manifest must still name the application id and the host-command permission
#   appstreamcli validate --no-net     the AppStream file (a warning fails it, not only an error)
#   desktop-file-validate              the desktop file
#
# That proves the files are well-formed. It does not prove that the Flatpak builds (runtime and extensions available,
# network at build time, the Zig and Ghostty downloads inside the sandbox) or runs: that needs a Linux machine.
#
# --container-build tries the real build from a Mac: in the same image, in a privileged container (flatpak-builder needs
# bubblewrap, which needs the privilege; Docker Desktop's Linux VM gives it), it installs the GNOME runtime, the SDK and
# the two extensions from Flathub into the Docker volume `holzwave-flatpak-data` (about 3 GB, kept between runs), builds the
# manifest with the working tree as source (without target, .git, node_modules, .planning) into the volume
# `holzwave-flatpak-build`, and checks the result: the binary and the three desktop files are installed, Zig is not, and
# `ldd` finds every library of the binary inside the runtime. It prints `flatpak-container-build: ok` as its last line only
# then. The container has the architecture of the Docker VM (arm64 on an Apple Silicon Mac), so it builds with the aarch64
# Zig archive of the manifest: it proves the manifest, the runtime and the SDK extensions, the network use and the
# source build, not the x86_64 archive and not a run (no display, no host to spawn on). The build takes a quarter of an
# hour; `docker volume rm holzwave-flatpak-build holzwave-flatpak-data` forgets everything.
#
# --engine-offline is the proof that the one part of the build that Flathub cannot fetch, the Zig-built terminal engine
# (libghostty-vt, built by Zig from a pinned Ghostty commit), builds with no network at all. Flathub forbids network access
# during a build, so every source must be named and hashed in advance. Two files below packaging/flatpak/generated/ come out
# of it; both are GENERATED by scripts/flatpak-zig-sources.sh, are not hand-written, and the owner may regenerate them by
# running this mode again (ghostty-pin.txt: the Ghostty commit that the engine crate pins; zig-sources.json: the Zig packages
# the library build really uses, each with a sha256 from two agreeing downloads). Stage A has the network: it reads the pin,
# checks Ghostty out at that commit on the host, builds the engine in the container of scripts/linux-container-test.sh
# with an empty scratch Zig cache (what that build fetches is the list of packages that are used, not the 37 that Ghostty
# lists), derives the two files, downloads exactly the listed sources and checks each sha256 before it unpacks it. Stage B
# runs `docker run --network none`: the Ghostty folder is GHOSTTY_SOURCE_DIR, the unpacked packages are
# GHOSTTY_ZIG_SYSTEM_DIR (both read-only), ZIG is the pinned Zig 0.17.0, and `cargo build --locked --offline --release -p
# libghostty-vt-sys` must produce libghostty-vt.a. It prints `flatpak-engine-offline: ok` as its last line only then. Only
# the architecture of the Docker VM is built (arm64 on an Apple Silicon Mac): Zig 0.17 crashes in the emulated amd64
# container, so the x86_64 engine build is not run and is untried. It does not build the app, run a Flatpak or run
# flatpak-builder. It writes only below target/flatpak-engine/, the two generated files and the cargo and image volumes of
# scripts/linux-container-test.sh; it publishes and signs nothing.
#
# The default mode is for the owner's Linux machine: it checks that `flatpak` and `flatpak-builder` exist and that the
# GNOME runtime, SDK and the two SDK extensions of the manifest are installed (and says how to install them), then
# builds with `flatpak-builder --user --install --force-clean` and prints how to run the result. The build needs the
# network (crates, npm packages, the Zig archive and the Zig packages of Ghostty): it is a local build. It writes only
# below target/ (the build directory and flatpak-builder's state directory) and into the user's Flatpak installation;
# it pushes, signs, tags and publishes nothing.
#
# Exit status: 0 when it passed (--check) or built, 1 when a validator failed or the build failed, 2 when a tool is
# missing (Docker, flatpak, flatpak-builder, a runtime) or the usage is wrong. A missing tool is a failed gate, never a
# skip.

APP_ID=ch.holzcloud.holzwave
RUNTIME_VERSION=51
EXTENSION_VERSION=26.08
IMAGE=holzwave-flatpak-check
BASE_IMAGE=ubuntu:26.04

here=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$here")
dir="$root/packaging/flatpak"
manifest="$dir/$APP_ID.yml"

mode=build
case "${1:-}" in
    "") ;;
    --check) mode=check ;;
    --container-build) mode=container ;;
    --engine-offline) mode=engine ;;
    *)
        echo "usage: sh scripts/build-flatpak.sh [--check | --container-build | --engine-offline]" >&2
        exit 2
        ;;
esac
if [ $# -gt 1 ]; then
    echo "usage: sh scripts/build-flatpak.sh [--check | --container-build | --engine-offline]" >&2
    exit 2
fi

for file in "$APP_ID.yml" "$APP_ID.metainfo.xml" "$APP_ID.desktop"; do
    if [ ! -f "$dir/$file" ]; then
        echo "flatpak: packaging/flatpak/$file is missing" >&2
        exit 2
    fi
done

# ---- --check ---------------------------------------------------------------------------------------------------

build_image() {
    echo "+ docker build -t $IMAGE (Dockerfile from stdin)"
    docker build -t "$IMAGE" --build-arg "BASE_IMAGE=$BASE_IMAGE" - <<'DOCKERFILE'
ARG BASE_IMAGE=ubuntu:26.04
FROM ${BASE_IMAGE}
ENV DEBIAN_FRONTEND=noninteractive
RUN apt-get update \
    && apt-get install -y --no-install-recommends appstream binutils ca-certificates desktop-file-utils elfutils flatpak \
        flatpak-builder git jq libarchive-tools patch xz-utils zstd \
    && rm -rf /var/lib/apt/lists/*
RUN flatpak remote-add --system --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo
DOCKERFILE
}

# What runs in the container: the three validators. `fail` stops the run, so the end is reached only when all passed.
CHECK=$(
    cat <<'CHECK'
set -u
fail() {
    echo "flatpak-check: FAILED: $*" >&2
    exit 1
}
id=ch.holzcloud.holzwave
cd /tmp || exit 1

echo "== flatpak-builder --show-manifest"
flatpak-builder --show-manifest "/pk/$id.yml" >manifest.json 2>manifest.err || fail "flatpak-builder cannot read the manifest: $(cat manifest.err)"
[ ! -s manifest.err ] || fail "flatpak-builder warns about the manifest: $(cat manifest.err)"
jq -e --arg id "$id" '.id == $id' manifest.json >/dev/null || fail "the parsed manifest has another application id"
jq -e '.["finish-args"] | index("--talk-name=org.freedesktop.Flatpak")' manifest.json >/dev/null || fail "the parsed manifest has no host-command permission"
jq -e '(.modules | length) >= 2' manifest.json >/dev/null || fail "the parsed manifest has fewer modules than expected"
echo "manifest: ok ($(jq -r '.runtime + "//" + .["runtime-version"]' manifest.json))"

echo "== appstreamcli validate --no-net"
appstreamcli validate --no-net "/pk/$id.metainfo.xml" || fail "appstreamcli validate"

echo "== desktop-file-validate"
desktop-file-validate "/pk/$id.desktop" || fail "desktop-file-validate"
echo "desktop file: ok"
CHECK
)

check() {
    if ! command -v docker >/dev/null 2>&1; then
        echo "flatpak-check: docker is missing: install Docker Desktop" >&2
        exit 2
    fi
    if ! docker info >/dev/null 2>&1; then
        echo "flatpak-check: the Docker daemon does not answer: start Docker Desktop" >&2
        exit 2
    fi
    if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
        build_image || {
            echo "flatpak-check: the image build failed" >&2
            exit 1
        }
    fi
    echo "+ docker run $IMAGE (three validators)"
    docker run --rm -v "$dir":/pk:ro "$IMAGE" sh -c "$CHECK" || {
        echo "flatpak-check: FAILED" >&2
        exit 1
    }
    echo "flatpak-check: ok"
}

# ---- --container-build -----------------------------------------------------------------------------------------

# What runs in the privileged container, with the working tree unpacked to /work.
BUILD=$(
    cat <<'BUILD'
set -u
fail() {
    echo "flatpak-container-build: FAILED: $*" >&2
    exit 1
}
id=ch.holzcloud.holzwave
ext=26.08
gnome=51
# The working tree is the standard input; it is read first and to the end.
mkdir -p /work && tar -x --no-same-owner -C /work 2>/dev/null || fail "unpacking the working tree"
echo "+ flatpak install (the runtime and the SDK extensions; kept in the volume)"
flatpak install --system -y --noninteractive flathub "org.gnome.Platform//$gnome" "org.gnome.Sdk//$gnome" \
    "org.freedesktop.Sdk.Extension.rust-stable//$ext" "org.freedesktop.Sdk.Extension.node26//$ext" </dev/null || fail "installing the runtime and the extensions"
echo "+ flatpak-builder (a quarter of an hour on a cold cache)"
flatpak-builder --disable-rofiles-fuse --state-dir=/build/state --force-clean /build/out "/work/packaging/flatpak/$id.yml" || fail "flatpak-builder"

echo "== the result"
out=/build/out/files
[ -x "$out/bin/holzwave-app" ] || fail "no binary in /app/bin"
for file in "share/applications/$id.desktop" "share/metainfo/$id.metainfo.xml" "share/icons/hicolor/128x128/apps/$id.png"; do
    [ -f "$out/$file" ] || fail "$file is not installed"
done
[ ! -e "$out/opt/zig" ] || fail "Zig is still in the app (a build tool must not ship)"
ls -l "$out/bin/holzwave-app"
missing=$(flatpak-builder --disable-rofiles-fuse --state-dir=/build/state --run /build/out "/work/packaging/flatpak/$id.yml" ldd /app/bin/holzwave-app 2>&1 | grep 'not found')
[ -z "$missing" ] || fail "libraries the runtime does not have: $missing"
echo "ldd: every library of the binary is in the runtime"
BUILD
)

container_build() {
    if ! command -v docker >/dev/null 2>&1; then
        echo "flatpak-container-build: docker is missing: install Docker Desktop" >&2
        exit 2
    fi
    if ! docker info >/dev/null 2>&1; then
        echo "flatpak-container-build: the Docker daemon does not answer: start Docker Desktop" >&2
        exit 2
    fi
    if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
        build_image || {
            echo "flatpak-container-build: the image build failed" >&2
            exit 1
        }
    fi
    echo "+ docker run --privileged $IMAGE (install the runtime, build, inspect)"
    code=$(mktemp "${TMPDIR:-/tmp}/holzwave-flatpak-code.XXXXXX") || exit 2
    COPYFILE_DISABLE=1 tar -c -C "$root" --exclude ./target --exclude ./.git --exclude node_modules --exclude ./.planning \
        --exclude ./app/dist . 2>/dev/null |
        {
            docker run --rm -i --privileged \
                -v holzwave-flatpak-data:/var/lib/flatpak \
                -v holzwave-flatpak-build:/build \
                "$IMAGE" sh -c "$BUILD"
            echo $? >"$code"
        }
    status=$(cat "$code")
    rm -f "$code"
    if [ "$status" != 0 ]; then
        echo "flatpak-container-build: FAILED (docker exit $status)" >&2
        exit 1
    fi
    echo "flatpak-container-build: ok"
}

# ---- --engine-offline ------------------------------------------------------------------------------------------

ENGINE_IMAGE=holzwave-linux-test

# Stage A, with the network: the engine build with an empty scratch Zig cache. What it fetched is the list of Zig packages
# that are used. The working tree is the standard input; the Ghostty checkout is /ghostty, the output folder /out.
STAGE_A=$(
    cat <<'STAGE_A'
set -u
fail() {
    echo "flatpak-engine-offline: FAILED: stage A: $*" >&2
    exit 1
}
tar -x --no-same-owner --warning=no-unknown-keyword -C /work || fail "unpacking the working tree"
cd /work || exit 1
[ "$(zig version)" = 0.17.0 ] || fail "Zig is not 0.17.0"
# Zig 0.17 unpacks the packages it fetches into zig-pkg/ next to build.zig of the project, so the checkout is a writable copy
# (the git source of a Flatpak build is writable too) and the folder it ends with is the list of packages that are used.
rm -rf /tmp/ghostty-src
cp -a /ghostty /tmp/ghostty-src || fail "copying the Ghostty checkout"
host=$(rustc -vV | sed -n 's/^host: //p')
echo "+ cargo fetch --locked (warms the cargo volumes for stage B)"
cargo fetch --locked --target "$host" || fail "cargo fetch"
rm -rf /tmp/zig-scratch /tmp/engine-target-a
export ZIG_GLOBAL_CACHE_DIR=/tmp/zig-scratch GHOSTTY_SOURCE_DIR=/tmp/ghostty-src CARGO_TARGET_DIR=/tmp/engine-target-a ZIG=/usr/local/bin/zig
echo "+ cargo build --locked --release -p libghostty-vt-sys (network on, empty Zig cache)"
cargo build --locked --release -p libghostty-vt-sys || fail "the engine build with the network on"
[ -d /tmp/ghostty-src/zig-pkg ] || fail "the build fetched no Zig package"
ls -1 /tmp/ghostty-src/zig-pkg >/out/zig-fetched.txt || fail "listing the fetched packages"
echo "stage A: the build fetched $(wc -l </out/zig-fetched.txt | tr -d ' ') Zig packages"
STAGE_A
)

# Stage B, with the network cut: the same build from the prepared folders only. A container that could still reach the
# network would not prove anything, so it is tried first.
STAGE_B=$(
    cat <<'STAGE_B'
set -u
fail() {
    echo "flatpak-engine-offline: FAILED: stage B: $*" >&2
    exit 1
}
if curl --silent --show-error --max-time 5 --output /dev/null https://deps.files.ghostty.org/ 2>/dev/null; then
    fail "the network is not cut"
fi
echo "stage B: the network is cut (no connection to deps.files.ghostty.org)"
tar -x --no-same-owner --warning=no-unknown-keyword -C /work || fail "unpacking the working tree"
cd /work || exit 1
[ "$(zig version)" = 0.17.0 ] || fail "Zig is not 0.17.0"
rm -rf /tmp/engine-target /tmp/ghostty-src
cp -a /ghostty /tmp/ghostty-src || fail "copying the Ghostty checkout"
export GHOSTTY_SOURCE_DIR=/tmp/ghostty-src GHOSTTY_ZIG_SYSTEM_DIR=/zig-pkgs CARGO_TARGET_DIR=/tmp/engine-target ZIG=/usr/local/bin/zig
echo "+ cargo build --locked --offline --release -p libghostty-vt-sys (no network)"
cargo build --locked --offline --release -p libghostty-vt-sys || fail "the offline engine build"
lib=$(find /tmp/engine-target/release/build -path '*/ghostty-install/lib/libghostty-vt.a' | head -n 1)
[ -n "$lib" ] && [ -s "$lib" ] || fail "the engine library libghostty-vt.a was not built"
header=$(dirname "$lib")/../include/ghostty/vt.h
[ -f "$header" ] || fail "the engine header ghostty/vt.h was not installed"
rm -rf /out/ghostty-install
cp -a "$(dirname "$lib")/.." /out/ghostty-install || fail "copying the engine out"
ls -l "$lib"
echo "stage B: libghostty-vt.a built with no network"
STAGE_B
)

# The working tree as a tar stream (as scripts/linux-container-test.sh sends it, without .git).
engine_tree_stream() {
    COPYFILE_DISABLE=1 tar -c -C "$root" --exclude target --exclude .git --exclude node_modules --exclude .planning .
}

# Run one stage in a container: engine_container <stage> <script> <docker arguments...>. The cargo volumes are those of
# scripts/linux-container-test.sh; the target directory of the build is inside the container, so each stage builds from nothing.
engine_container() {
    stage=$1
    script=$2
    shift 2
    code=$(mktemp "${TMPDIR:-/tmp}/holzwave-engine-code.XXXXXX") || exit 2
    engine_tree_stream | {
        docker run --rm -i --init \
            -v holzwave-linux-cargo-registry:/root/.cargo/registry \
            -v holzwave-linux-cargo-git:/root/.cargo/git \
            -e CARGO_TERM_COLOR=never \
            "$@" \
            "$ENGINE_IMAGE" sh -c "$script"
        echo $? >"$code"
    }
    status=$(cat "$code")
    rm -f "$code"
    if [ "$status" != 0 ]; then
        echo "flatpak-engine-offline: FAILED: stage $stage (docker exit $status)" >&2
        exit 1
    fi
}

engine_offline() {
    for tool in docker curl jq git tar; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            echo "flatpak-engine-offline: $tool is missing" >&2
            exit 2
        fi
    done
    if ! docker info >/dev/null 2>&1; then
        echo "flatpak-engine-offline: the Docker daemon does not answer: start Docker Desktop" >&2
        exit 2
    fi
    started=$(date +%s)
    work="$root/target/flatpak-engine"
    generated="$dir/generated"
    mkdir -p "$work" "$generated" || exit 1

    # The image with Rust and Zig 0.17.0, always the native architecture (no amd64 emulation: Zig crashes in it).
    HOLZWAVE_LINUX_ARCH= sh "$here/linux-container-test.sh" image || {
        echo "flatpak-engine-offline: the image $ENGINE_IMAGE could not be built" >&2
        exit 1
    }

    echo "== stage A (network on): the pin, the Ghostty checkout, the list of used Zig packages, the hashed sources"
    sh "$here/flatpak-zig-sources.sh" pin || exit 1
    commit=$(sed -n 's/^ghostty-commit=//p' "$generated/ghostty-pin.txt")
    repo=$(sed -n 's/^ghostty-repository=//p' "$generated/ghostty-pin.txt")
    src="$work/ghostty-src"
    if [ "$(git -C "$src" rev-parse HEAD 2>/dev/null)" != "$commit" ]; then
        rm -rf "$src"
        mkdir -p "$src" || exit 1
        echo "+ git fetch $repo $commit (shallow)"
        git -C "$src" init -q &&
            git -C "$src" -c advice.detachedHead=false fetch -q --depth 1 "$repo" "$commit" &&
            git -C "$src" -c advice.detachedHead=false checkout -q FETCH_HEAD || {
            echo "flatpak-engine-offline: the Ghostty checkout failed" >&2
            exit 1
        }
    fi
    [ "$(git -C "$src" rev-parse HEAD)" = "$commit" ] || {
        echo "flatpak-engine-offline: the Ghostty checkout is not at $commit" >&2
        exit 1
    }
    echo "ghostty: $commit"

    rm -rf "$work/stage-a" "$work/stage-b" "$work/scratch"
    mkdir -p "$work/stage-a" "$work/stage-b" || exit 1
    echo "+ docker run $ENGINE_IMAGE (stage A: the engine build with an empty Zig cache, network on)"
    engine_container A "$STAGE_A" -v "$src":/ghostty:ro -v "$work/stage-a":/out
    sh "$here/flatpak-zig-sources.sh" sources "$work/stage-a/zig-fetched.txt" "$work/scratch" || exit 1

    # The packages Zig looks up by hash name: exactly the sources of the generated file, each checked against its sha256
    # before it is unpacked.
    pkgs="$work/zig-pkgs"
    rm -rf "$pkgs"
    mkdir -p "$pkgs" "$work/scratch/dl" || exit 1
    sources="$generated/zig-sources.json"
    count=$(jq 'length' "$sources")
    jq -r '.[] | [.type, .url, (.sha256 // "-"), (.commit // "-"), .dest, ((."strip-components" // 0) | tostring)] | @tsv' "$sources" |
        while IFS="$(printf '\t')" read -r type url sha commit_of dest strip; do
            name=${dest#zig-pkgs/}
            case "$name" in "" | */* | .*) echo "flatpak-engine-offline: an odd dest in zig-sources.json: $dest" >&2; exit 1 ;; esac
            if [ "$type" = git ]; then
                mkdir -p "$pkgs/$name" || exit 1
                git -C "$pkgs/$name" init -q &&
                    git -C "$pkgs/$name" -c advice.detachedHead=false fetch -q --depth 1 "$url" "$commit_of" &&
                    git -C "$pkgs/$name" -c advice.detachedHead=false checkout -q FETCH_HEAD || exit 1
                [ "$(git -C "$pkgs/$name" rev-parse HEAD)" = "$commit_of" ] || exit 1
                rm -rf "$pkgs/$name/.git"
                continue
            fi
            [ "$type" = archive ] || exit 1
            file="$work/scratch/dl/$name"
            curl --proto '=https' --tlsv1.2 -fsSL --retry 3 -o "$file" "$url" || exit 1
            got=$(if command -v sha256sum >/dev/null 2>&1; then sha256sum "$file"; else shasum -a 256 "$file"; fi | cut -d' ' -f1)
            if [ "$got" != "$sha" ]; then
                echo "flatpak-engine-offline: sha256 of $url is $got, the sources file says $sha" >&2
                exit 1
            fi
            mkdir -p "$pkgs/$name" || exit 1
            tar -xf "$file" -C "$pkgs/$name" --strip-components="$strip" || exit 1
        done || {
        echo "flatpak-engine-offline: preparing the Zig packages failed" >&2
        exit 1
    }
    prepared=$(find "$pkgs" -mindepth 1 -maxdepth 1 -type d | wc -l | tr -d ' ')
    [ "$prepared" = "$count" ] || {
        echo "flatpak-engine-offline: $prepared package folders were prepared for $count sources" >&2
        exit 1
    }
    echo "prepared $prepared Zig packages from hashed sources"

    echo "== stage B (--network none): the engine build from the prepared folders only"
    echo "+ docker run --network none $ENGINE_IMAGE (stage B)"
    engine_container B "$STAGE_B" --network none -v "$src":/ghostty:ro -v "$pkgs":/zig-pkgs:ro -v "$work/stage-b":/out
    [ -s "$work/stage-b/ghostty-install/lib/libghostty-vt.a" ] || {
        echo "flatpak-engine-offline: FAILED: the engine library is not in target/flatpak-engine/stage-b" >&2
        exit 1
    }
    finished=$(date +%s)
    echo "engine build: arm64 only ($(docker run --rm "$ENGINE_IMAGE" uname -m)); the x86_64 engine build was not run"
    echo "time: $((finished - started)) seconds for the whole mode"
    echo "flatpak-engine-offline: ok"
}

# ---- the owner's Linux machine ---------------------------------------------------------------------------------

build() {
    if [ "$(uname -s)" != Linux ]; then
        echo "flatpak: this builds on Linux; on another system run: sh scripts/build-flatpak.sh --check" >&2
        exit 2
    fi
    for tool in flatpak flatpak-builder; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            echo "flatpak: $tool is missing: install it with your package manager (https://flatpak.org/setup/)" >&2
            exit 2
        fi
    done
    missing=""
    for ref in "org.gnome.Platform//$RUNTIME_VERSION" "org.gnome.Sdk//$RUNTIME_VERSION" \
        "org.freedesktop.Sdk.Extension.rust-stable//$EXTENSION_VERSION" "org.freedesktop.Sdk.Extension.node26//$EXTENSION_VERSION"; do
        flatpak info "$ref" >/dev/null 2>&1 || missing="$missing $ref"
    done
    if [ -n "$missing" ]; then
        echo "flatpak: the runtime or an SDK extension of the manifest is not installed:$missing" >&2
        echo "  add Flathub once:  flatpak remote-add --user --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo" >&2
        echo "  then install:      flatpak install --user flathub$missing" >&2
        exit 2
    fi

    state="$root/target/flatpak-state"
    out="$root/target/flatpak-build"
    mkdir -p "$state" || exit 1
    echo "+ flatpak-builder --user --install --force-clean (the build needs the network and takes a while)"
    flatpak-builder --user --install --force-clean --state-dir="$state" "$out" "$manifest" || {
        echo "flatpak: the build failed: see the message above; if the Flatpak cannot be built, it moves out of 0.0.1 (docs/flatpak.md)" >&2
        exit 1
    }
    echo
    echo "flatpak: built and installed for the user. Run it with:"
    echo "  flatpak run $APP_ID"
    echo "then work through row L10 of docs/test-plan.md."
}

case "$mode" in
    check) check ;;
    container) container_build ;;
    engine) engine_offline ;;
    *) build ;;
esac
