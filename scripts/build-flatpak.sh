app_cli_free() {
    for tool in docker tar; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            echo "app-cli-free: $tool is missing" >&2
            exit 2
        fi
    done
    if ! docker info >/dev/null 2>&1; then
        echo "app-cli-free: the Docker daemon does not answer: start Docker Desktop" >&2
        exit 2
    fi
    work="$root/target/flatpak-engine"
    if [ ! -f "$work/ghostty-src/build.zig" ] || [ ! -d "$work/zig-pkgs" ]; then
        echo "app-cli-free: the engine folders are missing: run  sh scripts/build-flatpak.sh --engine-offline  first" >&2
        exit 2
    fi
    HOLZWAVE_LINUX_ARCH= sh "$here/linux-container-test.sh" image || {
        echo "app-cli-free: the image $ENGINE_IMAGE could not be built" >&2
        exit 1
    }
    [ "$(docker image inspect -f '{{index .Config.Labels "ch.holzcloud.holzwave.node"}}' "$APP_IMAGE" 2>/dev/null)" = "$NODE_VERSION" ] ||
        build_app_image || {
        echo "app-cli-free: the image $APP_IMAGE could not be built" >&2
        exit 1
    }
    out="$root/target/flatpak-app"
    rm -rf "$out"
    mkdir -p "$out" || exit 1
    echo "+ docker run $APP_IMAGE (two builds of the app, network on)"
    code=$(mktemp "${TMPDIR:-/tmp}/holzwave-app-code.XXXXXX") || exit 2
    engine_tree_stream | {
        docker run --rm -i --init \
            -v holzwave-linux-cargo-registry:/root/.cargo/registry \
            -v holzwave-linux-cargo-git:/root/.cargo/git \
            -v holzwave-flatpak-app-target:/target-store \
            -v holzwave-linux-npm:/root/.npm \
            -v "$work/ghostty-src":/ghostty:ro \
            -v "$work/zig-pkgs":/zig-pkgs:ro \
            -v "$out":/out \
            -e CARGO_TERM_COLOR=never \
            "$APP_IMAGE" sh -c 'mkdir -p /work && tar -x --no-same-owner --warning=no-unknown-keyword -C /work && exec sh -c "$1"' sh "$APP_INNER"
        echo $? >"$code"
    }
    status=$(cat "$code")
    rm -f "$code"
    if [ "$status" != 0 ]; then
        echo "app-cli-free: FAILED (docker exit $status)" >&2
        exit 1
    fi
    cli_command=$(cat "$out/cli-command.txt")
    plain_command=$(cat "$out/plain-command.txt")
    if [ "$(cat "$out/verdict.txt")" != ok ]; then
        echo "app-cli-free: FAILED: a build is a development build ($(cat "$out/verdict.txt")); the CLI ran: $cli_command; plain cargo ran: $plain_command" >&2
        echo "app-cli-free: the Flatpak build then needs the Tauri CLI (a pinned npm package)" >&2
        exit 1
    fi
    generated="$dir/generated"
    mkdir -p "$generated" || exit 1
    {
        echo "# GENERATED by scripts/build-flatpak.sh --app-cli-free: do not edit by hand. The owner may regenerate it by running"
        echo "# that mode again (Docker, network on, after --engine-offline)."
        echo "#"
        echo "# The Tauri CLI, run as \`tauri build --no-bundle -v -- --locked\`, printed this cargo command for the app (copied from"
        echo "# its verbose output):"
        echo "#   Command \`$cli_command\`"
        echo "# Its page step, run first, was: \`$(cat "$out/cli-page-command.txt")\`; the same page build runs without the CLI as \`npm --prefix app run build\`."
        echo "# The command below is that command with --offline and -p holzwave-app (the build is run from the repository root)."
        echo "# The build script output of the app has no cargo:rustc-cfg=dev line in either build, so the page is embedded and the"
        echo "# app does not wait for a development server."
        echo "# Environment the build needs: CARGO_HOME (a folder inside the build directory), GHOSTTY_SOURCE_DIR (a writable"
        echo "# checkout of the pinned Ghostty commit), GHOSTTY_ZIG_SYSTEM_DIR (the packages of zig-sources.json), ZIG (Zig 0.17.0)."
        echo "$plain_command"
    } >"$generated/app-build-command.txt.new" || exit 1
    mv "$generated/app-build-command.txt.new" "$generated/app-build-command.txt" || exit 1
    echo "the CLI ran:  $cli_command"
    echo "plain cargo:  $plain_command"
    echo "wrote packaging/flatpak/generated/app-build-command.txt (arm64 only; the app was not started and not built with the network cut)"
    echo "app-cli-free: ok"
}

# ---- the owner's Linux machine ---------------------------------------------------------------------------------

build() {
    if [ "$(uname -s)" != Linux ]; then
        echo "flatpak: this builds on Linux; on another system run: sh scripts/build-flatpak.sh --check" >&2
        exit 2
    fi
    for tool in flatpak flatpak-builder; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            echo "flatpak: $tool is missing: install it with your package manager (https://flatpak.org/setup/)" >&2
            exit 2
        fi
    done
    missing=""
    for ref in "org.gnome.Platform//$RUNTIME_VERSION" "org.gnome.Sdk//$RUNTIME_VERSION" \
        "org.freedesktop.Sdk.Extension.rust-stable//$EXTENSION_VERSION" "org.freedesktop.Sdk.Extension.node26//$EXTENSION_VERSION"; do
        flatpak info "$ref" >/dev/null 2>&1 || missing="$missing $ref"
    done
    if [ -n "$missing" ]; then
        echo "flatpak: the runtime or an SDK extension of the manifest is not installed:$missing" >&2
        echo "  add Flathub once:  flatpak remote-add --user --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo" >&2
        echo "  then install:      flatpak install --user flathub$missing" >&2
        exit 2
    fi

    state="$root/target/flatpak-state"
    out="$root/target/flatpak-build"
    mkdir -p "$state" || exit 1
    echo "+ flatpak-builder --user --install --force-clean (the declared sources are downloaded first; the build steps have no network)"
    flatpak-builder --user --install --force-clean --state-dir="$state" "$out" "$manifest" || {
        echo "flatpak: the build failed: see the message above; if the Flatpak cannot be built, it moves out of 0.0.1 (docs/flatpak.md)" >&2
        exit 1
    }
    echo
    echo "flatpak: built and installed for the user. Run it with:"
    echo "  flatpak run $APP_ID"
    echo "then work through row L10 of docs/test-plan.md."
}

